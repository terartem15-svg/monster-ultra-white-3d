import type { Group } from 'three'

// Производные значения кадра, общие для всех объектов сцены. Их считает
// CanRig в самом начале кадра (useFrame с наименьшим приоритетом) из "сырых"
// motion.scroll/motion.intro, а куски банки, лёд и капли только читают —
// так сглаживание и кривые считаются один раз, и все объекты двигаются
// строго синхронно.
export const sceneState = {
  // Сглаженный прогресс скролл-сцены 0..1
  scroll: 0,
  // Насколько банка собрана: 0 — куски парят раздельно, 1 — цельная банка
  assemble: 0,
  // Насколько лёд разлетелся к краям кадра на скролле, 0..1
  spread: 0,
  // Сцена деталей: 0 — обычный вид, 1 — банка крупно в центре с выносками
  detail: 0,
  // Сглаженный прогресс вступления 0..1
  intro: 0,
  // Множитель амплитуды "парения": на скролле и при reduced motion меньше
  calm: 1,
}

